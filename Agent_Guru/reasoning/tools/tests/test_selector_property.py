from Agent_Guru.reasoning.tools.registry import ToolRegistry
from Agent_Guru.reasoning.tools.selector import ToolSelector


# Hypothesis strategies for generating test data
@st.composite
def intent_strategy(draw: Any) -> Intent:
    """Generate random Intent objects for testing.

    Args:
        draw: Hypothesis draw function

    Returns:
        Random Intent instance
    """
    # Choose random intent type
    intent_type = draw(st.sampled_from(list(IntentType)))

    # Generate random entities
    entity_count = draw(st.integers(min_value=0, max_value=5))
    entities: dict[str, Entity] = {}

    for i in range(entity_count):
        entity_name = draw(
            st.sampled_from(
                [
                    "duration_seconds",
                    "label",
                    "location",
                    "recipient",
                    "message",
                    "query",
                    "artist",
                    "song",
                ]
            )
        )
        entity_value = draw(
            st.one_of(
                st.integers(min_value=1, max_value=3600),
                st.text(min_size=1, max_size=50),
            )
        )

        entities[entity_name] = Entity(
            entity_type=draw(st.sampled_from(["duration", "text", "location", "person"])),
            value=entity_value,
            raw_text=str(entity_value),
            confidence=draw(st.floats(min_value=0.5, max_value=1.0)),
        )

    # Generate random input text
    original_input = draw(st.text(min_size=5, max_size=100))

    return Intent(
        intent_type=intent_type,
        entities=entities,
        confidence=draw(st.floats(min_value=0.5, max_value=1.0)),
        original_input=original_input,
    )


async def create_registry() -> ToolRegistry:
    """Create tool registry with example tools.

    Helper function to create registry inside tests (not a fixture).
    This avoids Hypothesis health check issues with function-scoped fixtures.
    """
    registry = ToolRegistry()

    # Register example tools
    timer_tool = SetTimerTool()
    await registry.register(timer_tool, timer_tool.metadata)

    cancel_tool = CancelTimerTool()
    await registry.register(cancel_tool, cancel_tool.metadata)

    weather_tool = WeatherTool()
    await registry.register(weather_tool, weather_tool.metadata)

    messaging_tool = MessagingTool()
    await registry.register(messaging_tool, messaging_tool.metadata)

    return registry


class TestToolSelectionProperties:
    """Property-based tests for tool selection.

    **Validates: Requirements 5.4**
    **Property 12: Selected tools have required parameters**
    """

    @settings(max_examples=100, suppress_health_check=[HealthCheck.function_scoped_fixture])
    @given(intent=intent_strategy())
    @pytest.mark.asyncio
    async def test_property_selected_tools_have_required_parameters(
        self,
        intent: Intent,
    ) -> None:
        """Property 12: For any selected tool, all required parameters must be present.

        This property validates that the tool selection engine never selects a tool
        unless all required parameters can be extracted from the intent.

        **Validates: Requirements 5.4**

        Args:
            intent: Random intent generated by Hypothesis
        """
        registry = await create_registry()
        selector = ToolSelector(registry)

        # Select tool for intent
        result = await selector.select_tool(intent)

        # If a tool was selected, verify all required parameters are present
        if result is not None:
            tool = result.tool
            parameters = result.parameters

            # Get required parameter names
            required_params = {p.name for p in tool.metadata.parameters if p.required}

            # Get provided parameter names
            provided_params = set(parameters.keys())

            # Assert: All required parameters must be present
            missing_params = required_params - provided_params
            assert len(missing_params) == 0, (  # nosec B101
                f"Selected tool '{tool.metadata.tool_id}' is missing required parameters: "
                f"{missing_params}. Required: {required_params}, Provided: {provided_params}"
            )

    @settings(max_examples=100, suppress_health_check=[HealthCheck.function_scoped_fixture])
    @given(intent=intent_strategy())
    @pytest.mark.asyncio
    async def test_property_selection_confidence_valid(
        self,
        intent: Intent,
    ) -> None:
        """Property: Selection confidence is always between 0.0 and 1.0.

        Args:
            intent: Random intent generated by Hypothesis
        """
